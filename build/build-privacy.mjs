// Render the hand-authored Pages privacy policy with the site’s shared shell.
import fs from "node:fs";
import path from "node:path";
import { marked } from "marked";
import { PUBLIC_DIR, ROOT } from "./config.mjs";
import { layout } from "./layout.mjs";

const source = path.join(ROOT, "site-src", "privacy.md");
const out = path.join(PUBLIC_DIR, "privacy", "index.html");

if (!fs.existsSync(source)) throw new Error(`missing privacy-policy source: ${source}`);

marked.setOptions({ mangle: false, headerIds: false, gfm: true });
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(
  out,
  layout({
    title: "Vorno — Privacy policy",
    description: "How Swagatar, LLC will handle data published through Vorno Pages.",
    canonical: "https://vorno.ai/privacy/",
    main: `<article class="prose policy">\n${marked.parse(fs.readFileSync(source, "utf8"))}\n</article>`,
  }),
);
fs.writeFileSync(
  path.join(path.dirname(out), "BUILD.txt"),
  "Generated by build/build-privacy.mjs from site-src/privacy.md.\n" +
    "Do not edit by hand — run `npm run privacy` in vorno-site instead.\n",
);
console.log(`[privacy] wrote ${path.relative(ROOT, out)}`);
